package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"log"
	"net/http"

	"github.com/go-chi/chi/v5"
)

// Task ...
type Task struct {
	ID           string   `json:"id"`
	Description  string   `json:"description"`
	Note         string   `json:"note"`
	Applications []string `json:"applications"`
}

func (t *Task) Validate() error {
	if t.ID == "" {
		return errors.New("user ID is required")
	} else if t.ID == "0" {
		return errors.New("user ID cannot be equal 0")
	}

	if t.Description == "" {
		return errors.New("description is required")
	}

	if t.Note == "" {
		return errors.New("note cannot be empty")
	}

	if len(t.Applications) == 0 {
		return errors.New("applications list cannot be empty")
	} else {
		for _, application := range t.Applications {
			if application == "" {
				return errors.New("applications cannot contain empty elements")
			}
		}
	}
	return nil
}

